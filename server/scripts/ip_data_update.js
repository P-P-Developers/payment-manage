const normalize = (str) => {
    return str
        ?.toLowerCase()
        .replace(/\.in/g, "")
        .replace(/[^a-z0-9]/g, "")
        .trim();
};

const updateData = [];   // 👈 final array for DB update
const noMatchPanels = [];

Panels.forEach((panel) => {
    const b = normalize(panel.panelName);

    let licenseData = Ip_data.filter((item) => {
        const a = normalize(item.panel_name);
        return a.includes(b) || b.includes(a);
    });

    if (licenseData.length === 0) {
        noMatchPanels.push(panel.panelName);
    } else {
        // 👇 har matched license ko object me convert karo
        licenseData.forEach((item) => {
            updateData.push({
                panelId: panel._id,
                paymentType: "IP Charges",
                amountReceived: 0,
                paymentMode: "UPI",
                bankName: "",
                quantity: Number(item.count),
                unitPrice: panel.ipCharges,
                billAmount: Number(item.count) * panel.ipCharges,
                remark: "update By System",
                dummyDate: item.createdAt,
                timestamp: item.createdAt
            });
        });
    }
});


